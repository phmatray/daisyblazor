// src/DaisyBlazor.Components/styles is the one source of the CSS preset. This script
// 1. regenerates the "literal classes" block of its safelist.css from the component sources,
//    so NuGet/npm consumers (who have no sources to @source) still get every class emitted;
// 2. copies the preset files into the npm package and the dotnet-new template.
// Run: node scripts/gen-styles.mjs [--check]   (--check fails if anything is stale; CI runs it)
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Scanner } from "@tailwindcss/oxide";
import { __unstable__loadDesignSystem } from "@tailwindcss/node";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const styles = resolve(root, "src/DaisyBlazor.Components/styles");
const file = resolve(styles, "safelist.css");
const BEGIN = "/* >>> generated by scripts/gen-safelist.mjs — do not edit by hand */";
const END = "/* <<< generated */";

const sources = ["DaisyBlazor.Components", "DaisyBlazor.Charts"].flatMap((p) =>
  ["razor", "cs"].map((ext) => ({ base: resolve(root, "src", p), pattern: `**/*.${ext}`, negated: false })));
const candidates = new Scanner({ sources }).scan();

const ds = await __unstable__loadDesignSystem(
  '@import "tailwindcss"; @plugin "daisyui" { themes: light --default; logs: false; }',
  { base: root });
const css = ds.candidatesToCss(candidates);
const classes = candidates
  .filter((c, i) => css[i] && !/^[A-Z]/.test(c)) // drop C# identifiers that happen to compile
  .sort();

const block = `${BEGIN}\n@source inline("${classes.join(" ")}");\n${END}`;
const current = readFileSync(file, "utf8");
const escape = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const safelist = current.includes(BEGIN)
  ? current.replace(new RegExp(`${escape(BEGIN)}[\\s\\S]*?${escape(END)}`), block)
  : `${current.trimEnd()}\n\n/* Every literal class found in the component sources. */\n${block}\n`;

const files = ["preset.css", "preset-core.css", "kit.css", "safelist.css"];
const content = (f) => (f === "safelist.css" ? safelist : readFileSync(resolve(styles, f), "utf8"));
const targets = [styles, resolve(root, "src/DaisyBlazor.Tailwind"), resolve(root, "templates/DaisyBlazor.Templates/templates/daisyblazor/Styles")]
  .flatMap((dir) => files.map((f) => ({ path: resolve(dir, f), text: content(f) })));
const read = (path) => { try { return readFileSync(path, "utf8"); } catch { return null; } };
const stale = targets.filter((t) => read(t.path) !== t.text);

if (process.argv.includes("--check")) {
  if (stale.length) {
    console.error(`stale: ${stale.map((t) => t.path.slice(root.length + 1)).join(", ")} — run node scripts/gen-styles.mjs`);
    process.exit(1);
  }
  console.log(`styles up to date (${classes.length} safelisted classes)`);
} else {
  for (const t of stale) writeFileSync(t.path, t.text);
  console.log(`${classes.length} safelisted classes; wrote ${stale.length} file(s)`);
}
