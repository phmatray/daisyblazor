// src/DaisyBlazor.Components/styles is the CSS preset shipped in the NuGet package. This script
// 1. vendors daisyUI's standalone bundles (daisyui.mjs, daisyui-theme.mjs) at the version pinned in
//    the root package.json, so consumers need no npm daisyUI;
// 2. regenerates the "literal classes" block of safelist.css from the component sources, so
//    NuGet consumers (who have no sources to @source) still get every class the components emit.
// Run: node scripts/gen-styles.mjs [--check]   (--check fails if anything is stale; CI runs it)
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { Scanner } from "@tailwindcss/oxide";
import { __unstable__loadDesignSystem } from "@tailwindcss/node";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const styles = resolve(root, "src/DaisyBlazor.Components/styles");
const check = process.argv.includes("--check");
const read = (path) => { try { return readFileSync(path, "utf8"); } catch { return null; } };
const stale = [];

// 1. daisyUI bundles — the first line records the vendored version.
const daisyVersion = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8")).devDependencies.daisyui;
const marker = `/*! daisyUI ${daisyVersion} standalone bundle (MIT), vendored by scripts/gen-styles.mjs */\n`;
for (const name of ["daisyui.mjs", "daisyui-theme.mjs"]) {
  const path = resolve(styles, name);
  if (read(path)?.startsWith(marker)) continue;
  if (check) { stale.push(path); continue; }
  const url = `https://github.com/saadeghi/daisyui/releases/download/v${daisyVersion}/${name}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  writeFileSync(path, marker + (await res.text()));
  console.log(`vendored ${name} ${daisyVersion}`);
}

// 2. Safelist of every literal class in the component sources that compiles to CSS.
const file = resolve(styles, "safelist.css");
const BEGIN = "/* >>> generated by scripts/gen-styles.mjs — do not edit by hand */";
const END = "/* <<< generated */";

const sources = ["DaisyBlazor.Components", "DaisyBlazor.Charts"].flatMap((p) =>
  ["razor", "cs"].map((ext) => ({ base: resolve(root, "src", p), pattern: `**/*.${ext}`, negated: false })));
const candidates = new Scanner({ sources }).scan();

const ds = await __unstable__loadDesignSystem(
  // safelist.css brings the kit's own @utility rules (font-heading) so their classes compile too.
  '@import "tailwindcss"; @plugin "./daisyui.mjs" { themes: light --default; logs: false; } @import "./safelist.css";',
  { base: styles });
const css = ds.candidatesToCss(candidates);
const classes = candidates
  .filter((c, i) => css[i] && !/^[A-Z]/.test(c)) // drop C# identifiers that happen to compile
  .sort();

const block = `${BEGIN}\n@source inline("${classes.join(" ")}");\n${END}`;
const current = read(file);
const escape = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const safelist = current.includes(BEGIN)
  ? current.replace(new RegExp(`${escape(BEGIN)}[\\s\\S]*?${escape(END)}`), block)
  : `${current.trimEnd()}\n\n/* Every literal class found in the component sources. */\n${block}\n`;
if (safelist !== current) {
  if (check) stale.push(file);
  else writeFileSync(file, safelist);
}

if (check && stale.length) {
  console.error(`stale: ${stale.map((p) => p.slice(root.length + 1)).join(", ")} — run node scripts/gen-styles.mjs`);
  process.exit(1);
}
console.log(`styles ${check ? "up to date" : "written"} (${classes.length} safelisted classes)`);
