// Bundles the D3 code the chart layouts use into src/DaisyBlazor.Charts/wwwroot/d3/, shipped in the
// DaisyBlazor.Charts NuGet so consumers never need npm. Layouts import from '../d3/<package>.mjs';
// this script reads those imports, writes one module per D3 package exporting only the names the
// layouts use, and lets esbuild move code two packages share into chunk-*.mjs files. A chart then
// loads only the D3 code its layout needs. Run after changing a layout's D3 imports or the D3
// versions in package.json; `--check` fails when the committed files are stale (CI).
import { build } from 'esbuild';
import { mkdtempSync, readdirSync, readFileSync, rmSync, mkdirSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const charts = fileURLToPath(new URL('../src/DaisyBlazor.Charts/wwwroot/', import.meta.url));
const layouts = join(charts, 'layouts');
const out = join(charts, 'd3');

// package -> names the layouts import from it
const used = new Map();
for (const file of readdirSync(layouts).filter(f => f.endsWith('.mjs'))) {
    const source = readFileSync(join(layouts, file), 'utf8');
    for (const [, names, pkg] of source.matchAll(/import\s*\{([^}]+)\}\s*from\s*'\.\.\/d3\/([a-z0-9-]+)\.mjs'/g)) {
        const set = used.get(pkg) ?? new Set();
        for (const name of names.split(',').map(n => n.trim().split(/\s+as\s+/)[0]).filter(Boolean)) {
            set.add(name);
        }
        used.set(pkg, set);
    }
}

const work = mkdtempSync(join(tmpdir(), 'daisyblazor-d3-'));
const entries = [...used.keys()].sort().map(pkg => {
    const entry = join(work, `${pkg}.mjs`);
    writeFileSync(entry, `export { ${[...used.get(pkg)].sort().join(', ')} } from '${pkg}';\n`);
    return entry;
});

const result = await build({
    entryPoints: entries, nodePaths: [fileURLToPath(new URL('../node_modules', import.meta.url))],
    bundle: true, splitting: true, format: 'esm', minify: true, write: false, legalComments: 'eof',
    target: 'es2020', outdir: out, entryNames: '[name]', chunkNames: 'chunk-[hash]', outExtension: { '.js': '.mjs' },
    banner: { js: '// D3 for DaisyBlazor.Charts. Generated by scripts/build-d3.mjs: do not edit.' },
});
rmSync(work, { recursive: true, force: true });

const files = new Map(result.outputFiles.map(f => [f.path.slice(out.length + 1), f.text]));
const current = existsSync(out) ? readdirSync(out) : [];

if (process.argv.includes('--check')) {
    const stale = [...files].filter(([name, text]) => !existsSync(join(out, name)) || readFileSync(join(out, name), 'utf8') !== text).map(([n]) => n);
    const extra = current.filter(name => !files.has(name));
    if (stale.length || extra.length) {
        console.error(`src/DaisyBlazor.Charts/wwwroot/d3/ is stale (${[...stale, ...extra].join(', ')}): run \`node scripts/build-d3.mjs\`.`);
        process.exit(1);
    }
    console.log('d3/ is up to date.');
} else {
    rmSync(out, { recursive: true, force: true });
    mkdirSync(out, { recursive: true });
    for (const [name, text] of files) {
        writeFileSync(join(out, name), text);
    }
    const total = [...files.values()].reduce((n, t) => n + t.length, 0);
    console.log(`Wrote ${files.size} files to ${out} (${(total / 1024).toFixed(1)} KB).`);
}
