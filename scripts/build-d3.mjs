// Bundles the compute-only D3 modules the D3-backed charts use into one ES module that ships in
// the DaisyBlazor.Charts NuGet (wwwroot/d3.mjs), so consumers never need npm. Run after changing
// the D3 versions in package.json; `--check` fails when the committed bundle is stale (CI).
import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../src/DaisyBlazor.Charts/wwwroot/d3.mjs', import.meta.url));
// No DOM modules (selection, axis, zoom, transition): layouts return data, Blazor renders the SVG.
const modules = ['d3-array', 'd3-scale', 'd3-shape', 'd3-hierarchy', 'd3-sankey', 'd3-chord',
    'd3-delaunay', 'd3-contour', 'd3-geo', 'd3-force', 'd3-time', 'd3-time-format', 'd3-format'];

const result = await build({
    stdin: { contents: modules.map(m => `export * from '${m}';`).join('\n'), resolveDir: process.cwd() },
    bundle: true, format: 'esm', minify: true, write: false, legalComments: 'eof', target: 'es2020',
    banner: { js: `// D3 compute modules for DaisyBlazor.Charts. Generated by scripts/build-d3.mjs: do not edit.` },
});
const code = result.outputFiles[0].text;

if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(out, 'utf8'); } catch { /* missing counts as stale */ }
    if (current !== code) {
        console.error('src/DaisyBlazor.Charts/wwwroot/d3.mjs is stale: run `node scripts/build-d3.mjs`.');
        process.exit(1);
    }
    console.log('d3.mjs is up to date.');
} else {
    writeFileSync(out, code);
    console.log(`Wrote ${out} (${(code.length / 1024).toFixed(1)} KB).`);
}
